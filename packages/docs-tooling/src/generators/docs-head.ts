/**
 * gen:docs-head: the docs header CSS that apps/web injects into <head>.
 *
 *   tsx src/generators/docs-head.ts [--check]
 *
 * Mintlify inlines apps/docs/styles/*.css as <style> elements deep in
 * <body>, after the header markup, so without help the browser first paints
 * Mintlify's two-row header and only then our one-row header (theme.css
 * sections 4-5b). apps/web's middleware (src/lib/docs-edge/head-inject.ts)
 * streams every docs HTML document through the solana.com proxy and adds a
 * render-blocking <link rel="stylesheet" href="/docs-head.css?v=<version>">
 * to <head>. This generator writes that file:
 *
 * - apps/web/public/docs-head.css: nojs.css, theme.css and assistant.css, in
 *   the order Mintlify inlines them (nojs before theme before assistant),
 *   with comments removed. Mintlify's own copy arrives later in the page and
 *   repeats the same rules, so applying them twice changes nothing.
 * - apps/web/src/lib/docs-edge/docs-head-version.ts: a content hash for the
 *   `?v=` cache buster (the CSS is served with a one-year immutable cache).
 *
 * `--check` fails when either file is missing or out of date (it runs in
 * `docs-tooling verify`). Output is deterministic.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { docsRoot as defaultDocsRoot, repoRoot } from "../lib/paths.ts";
import {
  emptyResult,
  finish,
  isMain,
  parseFlags,
  printResult,
  type GeneratorResult,
} from "./_lib.ts";

/** Sources, in Mintlify's inline order. Paths are relative to apps/docs. */
export const DOCS_HEAD_SOURCES = [
  "styles/nojs.css",
  "styles/theme.css",
  "styles/assistant.css",
] as const;

export const DOCS_HEAD_CSS_OUT = "apps/web/public/docs-head.css";
export const DOCS_HEAD_VERSION_OUT =
  "apps/web/src/lib/docs-edge/docs-head-version.ts";

const MARK =
  "GENERATED by packages/docs-tooling/src/generators/docs-head.ts. Do not edit: change apps/docs/styles and run `pnpm --filter @workspace/docs-tooling gen:docs-head`.";

/** Drops comments and blank lines; leaves every rule as written. */
export function stripCss(css: string, file = "css") {
  // A "/*" inside a string would be cut by the comment regex below.
  if (/["'][^"'\n]*\/\*/.test(css))
    throw new Error(`${file}: a string contains "/*"; strip by hand`);
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

export function buildDocsHead(docsRoot = defaultDocsRoot) {
  const parts = DOCS_HEAD_SOURCES.map((rel) => {
    const css = readFileSync(path.join(docsRoot, rel), "utf8");
    return `/* ${rel} */\n${stripCss(css, rel)}\n`;
  });
  const css = `/* ${MARK} */\n${parts.join("")}`;
  const version = createHash("sha256").update(css).digest("hex").slice(0, 12);
  const versionTs = `// ${MARK}\nexport const DOCS_HEAD_CSS_VERSION = "${version}";\n`;
  return { css, version, versionTs };
}

export function runDocsHead(
  opts: { check?: boolean; docsRoot?: string; outRoot?: string } = {},
): GeneratorResult {
  const check = !!opts.check;
  const outRoot = opts.outRoot ?? repoRoot;
  const r = emptyResult();
  const { css, versionTs } = buildDocsHead(opts.docsRoot);
  for (const [rel, body] of [
    [DOCS_HEAD_CSS_OUT, css],
    [DOCS_HEAD_VERSION_OUT, versionTs],
  ] as const) {
    const abs = path.join(outRoot, rel);
    const current = existsSync(abs) ? readFileSync(abs, "utf8") : null;
    if (current === body) continue;
    r.written.push(rel);
    if (!check) {
      mkdirSync(path.dirname(abs), { recursive: true });
      writeFileSync(abs, body);
    }
  }
  return finish(r, check);
}

if (isMain(import.meta.url)) {
  const { check } = parseFlags(process.argv.slice(2));
  const r = runDocsHead({ check });
  printResult("gen:docs-head", r, check);
  if (!r.ok) process.exit(1);
}
