/** Same slug rule as the legacy `toDocumentationTagSlug`. */
export function tagSlug(tag: string) {
  return tag
    .trim()
    .normalize("NFKD")
    .toLocaleLowerCase("en")
    .replace(/\p{Mark}+/gu, "")
    .replace(/[^\p{Letter}\p{Number}]+/gu, "-")
    .replace(/^-+|-+$/g, "");
}

interface PageInfo {
  /** docs-root relative path without extension. */
  page: string;
  url: string;
  title: string;
  description?: string;
}

const FM_RE = /^---\r?\n([\s\S]*?)\r?\n---[ \t]*(?:\r?\n|$)/;

function frontmatter(source: string): Record<string, unknown> {
  const m = FM_RE.exec(source);
  if (!m) return {};
  const v: unknown = YAML.parse(m[1]!);
  return isRecord(v) ? v : {};
}

const urlOf = (page: string) => `/${page.replace(/(^|\/)index$/, "")}`;

function readPage(docsRoot: string, page: string): PageInfo | undefined {
  for (const ext of [".mdx", ".md"]) {
    const abs = path.join(docsRoot, page + ext);
    if (!existsSync(abs)) continue;
    const fm = frontmatter(readFileSync(abs, "utf8"));
    const title =
      (typeof fm.sidebarTitle === "string" && fm.sidebarTitle) ||
      (typeof fm.title === "string" && fm.title) ||
      page;
    return {
      page,
      url: urlOf(page),
      title,
      description:
        typeof fm.description === "string" ? fm.description : undefined,
    };
  }
  return undefined;
}

/** `<lang>/P` when it exists, else the English `P` (decisions.md). */
function localized(
  docsRoot: string,
  enPage: string,
  lang: string,
): PageInfo | undefined {
  if (lang !== DEFAULT_LOCALE) {
    const loc = readPage(docsRoot, `${lang}/${enPage}`);
    if (loc) return loc;
  }
  return readPage(docsRoot, enPage);
}

// ---------------------------------------------------------------------------
// Navigation (WP6 output) -> tab roots
// ---------------------------------------------------------------------------

function firstPage(entry: unknown): string | undefined {
  if (typeof entry === "string") return entry;
  if (!isRecord(entry)) return undefined;
  if (typeof entry.root === "string") return entry.root;
  for (const key of ["pages", "groups"]) {
    const list = entry[key];
    if (Array.isArray(list))
      for (const e of list) {
        const p = firstPage(e);
        if (p) return p;
      }
  }
  return undefined;
}

function resolveLabel(
  label: unknown,
  labels: Record<string, unknown>,
): string | undefined {
  if (typeof label !== "string") return undefined;
  if (!label.startsWith("@label:")) return label;
  const id = label.slice("@label:".length);
  if (typeof labels[id] === "string") return labels[id] as string;
  let cur: unknown = labels;
  for (const part of id.split(".")) cur = isRecord(cur) ? cur[part] : undefined;
  return typeof cur === "string" ? cur : undefined;
}

/** Tab roots from `navigation/<lang>.json`, or undefined when absent. */
export function tabsFromNavigation(
  docsRoot: string,
  lang: string,
): TabRoot[] | undefined {
  const file = path.join(docsRoot, "navigation", `${lang}.json`);
  if (!existsSync(file)) return undefined;
  const nav: unknown = JSON.parse(readFileSync(file, "utf8"));
  const labelsFile = path.join(
    docsRoot,
    "navigation",
    "labels",
    `${lang}.json`,
  );
  const labels: unknown = existsSync(labelsFile)
    ? JSON.parse(readFileSync(labelsFile, "utf8"))
    : {};
  const tabs = isRecord(nav) && Array.isArray(nav.tabs) ? nav.tabs : [];
  const out: TabRoot[] = [];
  for (const t of tabs) {
    if (!isRecord(t) || t.hidden === true) continue;
    // External-link tabs have an href and no pages.
    const p = firstPage(t);
    if (!p) continue;
    // Locale navs hold `<lang>/docs/...` or English fallbacks; normalise to EN.
    const page = p.replace(new RegExp(`^${lang}/`), "");
    out.push({
      label: resolveLabel(t.tab, isRecord(labels) ? labels : {}),
      // The navigation tabs carry no icons (the Luma header has no room for
      // them); the tag page's tab cards keep theirs from DEFAULT_TABS.
      icon:
        typeof t.icon === "string"
          ? t.icon
          : DEFAULT_TABS.find((d) => d.page === page)?.icon,
      page,
    });
  }
  return out;
}

// ---------------------------------------------------------------------------
// Tags
// ---------------------------------------------------------------------------

export interface Tag {
  slug: string;
  label: string;
  pages: PageInfo[];
}

/** Pages of one language grouped by `documentationTags`. */
export function collectTags(docsRoot: string, lang: string): Tag[] {
  const prefix =
    lang === DEFAULT_LOCALE ? "developers/docs/" : `${lang}/developers/docs/`;
  const tags = new Map<string, Tag>();
  for (const abs of listContentPages(docsRoot)) {
    const rel = toPosix(path.relative(docsRoot, abs));
    if (!rel.startsWith(prefix)) continue;
    const source = readFileSync(abs, "utf8");
    if (!source.includes("documentationTags")) continue;
    const fm = frontmatter(source);
    const raw = fm.documentationTags;
    if (!Array.isArray(raw)) continue;
    const page = readPage(docsRoot, rel.replace(/\.mdx?$/, ""))!;
    const seen = new Set<string>();
    for (const r of raw) {
      if (typeof r !== "string") continue;
      const label = r.trim();
      const slug = tagSlug(label);
      if (!slug || seen.has(slug)) continue;
      seen.add(slug);
      const tag = tags.get(slug) ?? { slug, label, pages: [] };
      tag.pages.push(page);
      tags.set(slug, tag);
    }
  }
  return [...tags.values()]
    .map((t) => ({
      ...t,
      pages: t.pages.sort((a, b) => a.title.localeCompare(b.title, "en")),
    }))
    .sort((a, b) => a.label.localeCompare(b.label, "en"));
}

// ---------------------------------------------------------------------------
// Rendering
// ---------------------------------------------------------------------------

function card(
  title: string,
  href: string,
  icon: string | undefined,
  body: string | undefined,
) {
  // A plain string attribute (single-quoted when the title has a double
  // quote, as the formatter prefers); the formatter re-wraps long `{"…"}`
  // expressions but never a string.
  const attrs = [
    !title.includes('"')
      ? `title="${title}"`
      : !title.includes("'")
        ? `title='${title}'`
        : jsAttr("title", title),
    `href="${href}"`,
  ];
  if (icon) attrs.push(`icon="${icon}"`);
  // Same rule as the formatter: one line if it fits in 80 columns, else one
  // attribute per line.
  const end = body ? ">" : " />";
  const flat = `  <Card ${attrs.join(" ")}${end}`;
  const open =
    flat.length <= 80
      ? flat
      : `  <Card\n${attrs
          .map((a) =>
            a.length + 4 > 80 && a.includes("={")
              ? `    ${a.replace(/=\{(.*)\}$/, "={\n      $1\n    }")}`
              : `    ${a}`,
          )
          .join("\n")}\n  ${body ? ">" : "/>"}`;
  if (!body) return open;
  return `${open}\n${wrap(mdInline(body), "    ")}\n  </Card>`;
}

/**
 * Greedy word wrap at 80 columns, indentation included: the repo formatter
 * (oxfmt, `proseWrap: always`) wraps English content pages on commit, so the
 * generated page must already be in that shape or `--check` would drift.
 */
export function wrap(s: string, indent: string, width = 80) {
  const lines: string[] = [];
  let line = "";
  for (const word of s.split(/\s+/).filter(Boolean)) {
    if (line && indent.length + line.length + 1 + word.length > width) {
      lines.push(indent + line);
      line = word;
    } else line = line ? `${line} ${word}` : word;
  }
  if (line) lines.push(indent + line);
  return lines.join("\n");
}

// No blank lines between cards: oxfmt de-indents JSX children that follow a
// blank line, which would also make `--check` drift.
const columns = (cards: string[]) =>
  `<Columns cols={2}>\n${cards.join("\n")}\n</Columns>\n`;

export function renderBody(
  docsRoot: string,
  lang: string,
  tags: Tag[],
  tabs: readonly TabRoot[],
): string {
  const parts: string[] = [
    `{/* ${GENERATED_MARK}tags.ts from documentationTags frontmatter and navigation/${lang}.json (spec §2.2 tab roots until it exists). Do not edit: run \`pnpm --filter @workspace/docs-tooling gen:tags\`. */}\n`,
  ];
  for (const tag of tags) {
    // `## Label` gets the docs heading anchor; an explicit id is not supported
    // on markdown headings, so the slug must match the legacy tag URL.
    parts.push(`## ${tag.label}\n`);
    parts.push(
      columns(
        tag.pages.map((p) => card(p.title, p.url, undefined, p.description)),
      ),
    );
  }
  const tabCards: string[] = [];
  for (const tab of tabs) {
    const target = localized(docsRoot, tab.page, lang);
    if (!target) continue; // page not written yet (e.g. a NEW hub)
    tabCards.push(
      card(tab.label ?? target.title, target.url, tab.icon, target.description),
    );
  }
  if (tags.length && tabCards.length) parts.push("## Browse by section\n");
  if (tabCards.length) parts.push(columns(tabCards));
  return parts.join("\n");
}

/** The full file: existing frontmatter verbatim + generated body. */
export function renderTagsPage(existing: string, body: string): string {
  const m = FM_RE.exec(existing);
  const fm = m ? m[0].replace(/\r?\n?$/, "\n") : "";
  return `${fm}\n${body}`;
}

export interface TagsOptions extends GeneratorOptions {
  /** Only this language ("en" or a locale folder). */
  lang?: string;
}

export function generateTags(opts: TagsOptions = {}): GeneratorResult {
  const docsRoot = opts.docsRoot ?? defaultDocsRoot;
  const r: GeneratorResult = { written: [], problems: [], ok: true };
  const langs = [DEFAULT_LOCALE, ...TARGET_LOCALES].filter(
    (l) => !opts.lang || l === opts.lang,
  );
  for (const lang of langs) {
    const rel = lang === DEFAULT_LOCALE ? TAGS_PAGE : `${lang}/${TAGS_PAGE}`;
    const abs = path.join(docsRoot, rel);
    if (!existsSync(abs)) {
      if (lang === DEFAULT_LOCALE)
        r.problems.push({ level: "error", file: rel, message: "missing" });
      continue;
    }
    const tabs =
      tabsFromNavigation(docsRoot, lang) ??
      DEFAULT_TABS.map((t) =>
        // Default English labels only for English; locales use page titles.
        lang === DEFAULT_LOCALE ? t : { ...t, label: undefined },
      );
    const body = renderBody(docsRoot, lang, collectTags(docsRoot, lang), tabs);
    const have = readFileSync(abs, "utf8");
    const want = renderTagsPage(have, body);
    if (want === have) continue;
    r.written.push(rel);
    if (!opts.check) writeFileSync(abs, want);
  }
  r.written.sort();
  r.ok =
    !r.problems.some((p) => p.level === "error") &&
    !(opts.check && r.written.length);
  return r;
}

const entry = process.argv[1];
if (entry && path.resolve(entry) === new URL(import.meta.url).pathname) {
  const check = process.argv.includes("--check");
  const i = process.argv.indexOf("--locale");
  const lang = i > 0 ? process.argv[i + 1] : undefined;
  const r = generateTags({ check, lang });
  const verb = check ? "stale" : "wrote";
  console.log(
    `gen:tags: ${check ? "would write" : "wrote"} ${r.written.length} page(s); ${r.problems.length} problem(s)`,
  );
  for (const f of r.written) console.log(`  ${verb}: ${f}`);
  for (const p of r.problems)
    console.log(`  ${p.level} ${p.file ?? ""}: ${p.message}`);
  process.exit(r.ok ? 0 : 1);
}
