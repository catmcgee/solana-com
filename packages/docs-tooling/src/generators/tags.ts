/**
 * The static `/docs/tags` page, per language.
 *
 * The Fumadocs app grouped pages by the opt-in `documentationTags`
 * frontmatter at request time and served `/docs/tags/<tag>` detail pages.
 * The docs have no taxonomy feature, so this generator writes the whole
 * page body:
 *
 * - one `## <Tag>` section per tag (sorted), listing its pages as cards. The
 *   heading anchor is the tag slug, so `/docs/tags/<tag>` can redirect to
 *   `/docs/tags#<tag>` (apps/web, WP9);
 * - a card per navigation tab ("browse by section"). The tabs come from
 *   `navigation/<lang>.json` when it exists, else from the spec §2.2
 *   tab roots.
 *
 * No page uses `documentationTags` today, so the page is the section index.
 * The frontmatter (title, description, translated per locale) is kept
 * byte-for-byte; only the body below it is generated. Locale cards link to
 * the translated page when it exists, else the English page (decisions.md).
 *
 *   tsx src/generators/tags.ts [--check]
 */
import {
  existsSync,
  readdirSync,
  readFileSync,
  statSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { DEFAULT_LOCALE, TARGET_LOCALES } from "../lib/locales.ts";
import { docsRoot as defaultDocsRoot, toPosix } from "../lib/paths.ts";

// ---------------------------------------------------------------------------
// Generator plumbing. Self-contained on purpose: the WP8b helpers in
// `_lib.ts` follow the same conventions (GENERATED header, --check) but are
// still changing.
// ---------------------------------------------------------------------------

export const GENERATED_MARK =
  "GENERATED by packages/docs-tooling/src/generators/";

export interface GeneratorOptions {
  /** Docs content root (defaults to apps/docs). Tests point this at a temp dir. */
  docsRoot?: string;
  /** Compute in memory and report; never write. */
  check?: boolean;
}

export interface GeneratorResult {
  /** Docs-root relative files written (or, with `check`, stale). */
  written: string[];
  problems: { level: "error" | "warn"; file?: string; message: string }[];
  /** `false` when `check` found drift or an error was reported. */
  ok: boolean;
}

const isRecord = (v: unknown): v is Record<string, unknown> =>
  typeof v === "object" && v !== null && !Array.isArray(v);

/** A plain-text value as a JSX expression attribute (`name={"..."}`). */
const jsAttr = (name: string, s: string) => `${name}={${JSON.stringify(s)}}`;

/** Inline markdown on one line, with `{ } < >` escaped (no JSX/expressions). */
const mdInline = (s: string) =>
  s
    .replace(/\s*\n\s*/g, " ")
    .trim()
    .replace(/[{}<>]/g, (c) => `\\${c}`);

/** Every `.mdx` page under the docs root (snippets excluded), sorted. */
function listContentPages(root: string): string[] {
  const out: string[] = [];
  const rec = (dir: string) => {
    for (const name of readdirSync(dir).sort()) {
      if (name.startsWith(".") || name === "node_modules") continue;
      const abs = path.join(dir, name);
      if (statSync(abs).isDirectory()) {
        if (dir === root && (name === "snippets" || name === "docs-assets"))
          continue;
        rec(abs);
      } else if (name.endsWith(".mdx")) out.push(abs);
    }
  };
  if (existsSync(root)) rec(root);
  return out;
}

export const TAGS_PAGE = "developers/docs/tags/index.mdx";

export interface TabRoot {
  /** Label shown on the card (tab name), or undefined to use the page title. */
  label?: string;
  icon?: string;
  /** Docs-root relative page path without extension, English. */
  page: string;
}

