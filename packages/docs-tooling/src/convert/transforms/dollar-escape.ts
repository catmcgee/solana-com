/**
 * Escape prose dollar signs: `$0.88 or $20` -> `\$0.88 or \$20`.
 *
 * The renderer at conversion time always ran remark-math with single-dollar inline math, so two
 * `$` in one paragraph, heading or table row turn everything between them
 * into KaTeX ("$5 or $50" renders as math italic "5or"). Fumadocs had no
 * math, so legacy prose never escaped `$`. No page in this site intends
 * math.
 *
 * Rule: in every paragraph, heading and table row whose source holds two or
 * more `$` (anywhere: text, inline code, JSX attributes, since the math
 * tokenizer scans raw characters for its closing run), every unescaped `$`
 * in prose text becomes `\$`. Code (fences, inline code) and JSX attribute
 * values are never touched. A lone `$` in a block cannot open math and is
 * left alone. Idempotent: an escaped `$` is not escaped again.
 *
 * Text nodes copied from the source are re-emitted from their source slice
 * (so other escapes and entities stay byte-identical); text generated by
 * earlier transforms is split around `\$` raw nodes.
 *
 * `findMathRisks` is the verify-side check (same rule, reports instead of
 * fixing); it also covers snippets, which convert does not touch.
 */
import type { AstNode, Transform } from "../../types.ts";
import { text } from "./_wp2.ts";

type Pos = { start?: { offset?: number }; end?: { offset?: number } };
const BLOCKS = new Set(["paragraph", "heading", "tableRow"]);

function slice(n: AstNode, source: string | undefined): string | undefined {
  const p = n.position as Pos | undefined;
  const s = p?.start?.offset;
  const e = p?.end?.offset;
  if (source === undefined || s === undefined || e === undefined)
    return undefined;
  return source.slice(s, e);
}

/** All text a block's source could contain (fallback when generated). */
function flatValue(n: AstNode): string {
  if (typeof n.value === "string") return n.value;
  return (n.children ?? []).map(flatValue).join("");
}

/** Unescaped `$` in markdown source (a `\` escapes the next character). */
function escapeSource(src: string): string {
  let out = "";
  for (let i = 0; i < src.length; i++) {
    const c = src[i]!;
    if (c === "\\" && i + 1 < src.length) {
      out += c + src[i + 1];
      i++;
    } else out += c === "$" ? "\\$" : c;
  }
  return out;
}

/**
 * Does the source slice still describe this text node's value? (False when
 * an earlier transform edited the value in place.) Escapes and character
 * references are ignored; letters, digits and `$` must match exactly.
 */
function sliceMatches(src: string, value: string): boolean {
  const norm = (x: string) => x.replace(/[^\p{L}\p{N}$]/gu, "");
  const plain = src
    .replace(/\\([!-/:-@[-`{-~])/g, "$1")
    .replace(/&(?:#x?[0-9a-f]+|[a-z][a-z0-9]*);/gi, "");
  return norm(plain) === norm(value);
}

/** Text nodes (outside code and JSX attributes) under a block. */
function textNodes(
  n: AstNode,
  out: { node: AstNode; parent: AstNode }[] = [],
): { node: AstNode; parent: AstNode }[] {
  for (const c of n.children ?? []) {
    if (c.type === "text") out.push({ node: c, parent: n });
    else if (c.children && c.type !== "code" && c.type !== "inlineCode")
      textNodes(c, out);
  }
  return out;
}

function atRisk(block: AstNode, source: string | undefined): boolean {
  const src = slice(block, source) ?? flatValue(block);
  return (src.match(/\$/g)?.length ?? 0) >= 2;
}

/** Does this text node hold an unescaped `$`? */
function hasUnescaped(t: AstNode, source: string | undefined): boolean {
  const value = String(t.value ?? "");
  if (!value.includes("$")) return false;
  const src = slice(t, source);
  if (src !== undefined && sliceMatches(src, value))
    return escapeSource(src) !== src;
  return true;
}

function escapeText(t: AstNode, source: string | undefined): AstNode[] {
  const value = String(t.value ?? "");
  const src = slice(t, source);
  if (src !== undefined && sliceMatches(src, value))
    return [{ type: "raw", value: escapeSource(src) }];
  const parts = value.split("$");
  const out: AstNode[] = [];
  parts.forEach((p, i) => {
    if (i > 0) out.push({ type: "raw", value: "\\$" });
    if (p) out.push(text(p));
  });
  return out;
}

function visitBlocks(n: AstNode, fn: (block: AstNode) => void): void {
  if (n.type === "code" || n.type === "inlineCode") return;
  if (BLOCKS.has(n.type)) {
    fn(n);
    return;
  }
  for (const c of n.children ?? []) visitBlocks(c, fn);
}

export function escapeDollars(tree: AstNode, source?: string): number {
  let changed = 0;
  visitBlocks(tree, (block) => {
    if (!atRisk(block, source)) return;
    for (const { node, parent } of textNodes(block)) {
      if (!hasUnescaped(node, source)) continue;
      const kids = parent.children!;
      const i = kids.indexOf(node);
      kids.splice(i, 1, ...escapeText(node, source));
      changed++;
    }
  });
  return changed;
}

export interface MathRisk {
  line: number;
  text: string;
}

/** Blocks that single-dollar math would render (partly) as KaTeX. */
export function findMathRisks(tree: AstNode, source: string): MathRisk[] {
  const risks: MathRisk[] = [];
  visitBlocks(tree, (block) => {
    if (!atRisk(block, source)) return;
    if (!textNodes(block).some(({ node }) => hasUnescaped(node, source)))
      return;
    const p = block.position as { start?: { line?: number } } | undefined;
    risks.push({
      line: p?.start?.line ?? 0,
      text: (slice(block, source) ?? flatValue(block)).slice(0, 120),
    });
  });
  return risks;
}

export const transform: Transform = {
  name: "dollar-escape",
  order: 950,
  owner: "WP12",
  appliesTo: (source) => /\$[^]*\$/.test(source),
  run(tree, file) {
    escapeDollars(tree, file.source);
  },
};
