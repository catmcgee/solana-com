/**
 * api-method: `<APIMethod>` RPC method pages and the
 * Surfpool `<*Rpc />` method-list components.
 *
 * 1. `<APIMethod>` (71 en pages, 1,261 files in all locales), after
 *    `return-type` has converted its `### !!result` sections:
 *
 *    ```jsonc !!request curl     -> <RequestExample> ```bash cURL
 *    ```ts !!request title="Kit" ->                  ```ts Kit   (etc.)
 *    ### !params                 -> ## Parameters
 *    #### !! pubkey / !type ...  -> <ParamField body="pubkey" type required default>
 *    ##### !! commitment         ->   <Expandable title="properties"> <ParamField …>
 *
 *    The `<ResponseExample>` that `return-type` left at the end of the block
 *    moves up next to the `<RequestExample>`; the "Result" heading and fields
 *    stay after "Parameters". `<APIMethod>` itself is unwrapped.
 *
 *    - cURL: the `!!request curl` JSON body (comments removed) inside
 *      `curl https://api.devnet.solana.com -s -X POST -H … -d '…'`, exactly
 *      what the old component built at render time.
 *    - WebSocket pages (`rpc/websocket/*`): the request is a WebSocket
 *      message, so it is shown as a `json WebSocket` fence. The old site
 *      wrapped it in an HTTP cURL command, which the RPC answers with
 *      "Method not found".
 *    - `!values` -> a `Values: …` line; `!optional` -> not required;
 *      `!hover` lines are removed; `!collapse … collapsed` -> `expandable`.
 *    - No `api:` frontmatter / playground: JSON-RPC positional params do not
 *      fit ParamField bodies.
 *    - Frontmatter: `hideTableOfContents` / `mode: wide` are removed. A page
 *      with `<RequestExample>` shows the examples in the right column where
 *      the TOC would be (the old two-panel layout); `mode: wide` would instead
 *      stack them above the page title.
 *
 * 2. Surfpool pages (`tools/surfpool/rpc/*`, 7 pages x 19 locales):
 *    `<AccountsRpc />` -> `import SurfpoolAccounts from
 *    "/snippets/rpc/surfpool/accounts.mdx";` + `<SurfpoolAccounts />`. The
 *    snippets are generated by `src/generators/surfpool-rpc.ts`; every locale
 *    imports the same English snippet. MDX snippets are server-rendered (the
 *    setup SSR probe), so the method reference reads without JavaScript and
 *    its `##` method headings feed the native TOC.
 *
 * Order 89: after `return-type` (87), before the WP2 fence/annotation
 * transforms (100+), which would otherwise rewrite the `!!request` metas and
 * `!hover` lines this transform consumes.
 */
import type { AstNode, Transform } from "../../types.ts";
import {
  SURFPOOL_COMPONENTS,
  surfpoolImportName,
  surfpoolSnippetPath,
  type SurfpoolCategory,
} from "../../generators/surfpool-rpc.ts";
import {
  DEVNET_RPC,
  codeNode,
  curlCommand,
  fenceMeta,
  fieldChildren,
  findJsx,
  heading,
  hikeCodeTitle,
  isJsx,
  isWebSocketPage,
  jsx,
  paragraph,
  parseHikeSections,
  plainFence,
  renderField,
  replaceNode,
  reportValues,
  sectionDepth,
  stripAnnotations,
  text,
  toText,
  walk,
  type HikeCode,
} from "./_rpc.ts";
import type { ConvertContext, ConvertFile } from "../../types.ts";

const SURFPOOL_RE = new RegExp(
  `<(?:${Object.keys(SURFPOOL_COMPONENTS).join("|")})\\b`,
);

export const transform: Transform = {
  name: "api-method",
  order: 89,
  appliesTo: (src) => src.includes("<APIMethod") || SURFPOOL_RE.test(src),
  run(tree, file, ctx) {
    const methods = findJsx(tree, "APIMethod");
    if (methods.length) {
      const depth = sectionDepth(tree);
      for (const { node, parent } of methods)
        replaceNode(parent, node, convertMethod(node, depth, file, ctx));
      delete file.frontmatter.hideTableOfContents;
      if (file.frontmatter.mode === "wide") delete file.frontmatter.mode;
    }
    convertSurfpool(tree);
  },
};

function requestFence(
  c: HikeCode,
  file: ConvertFile,
  ctx: ConvertContext,
  where: string,
): AstNode {
  const lang = String(c.node.lang ?? "");
  const isCurl = /(^|\s)curl(\s|$)/.test(c.title);
  if (!isCurl && lang !== "jsonc" && lang !== "json")
    return plainFence(c, { ctx, where });
  const cleaned = stripAnnotations(String(c.node.value ?? ""), lang);
  const body = cleaned.value.trim();
  try {
    JSON.parse(body);
  } catch {
    ctx.warn(`${where}: request body is not valid JSON after comment removal`);
  }
  if (isWebSocketPage(file)) {
    return codeNode("json", fenceMeta("WebSocket"), body);
  }
  if (!isCurl) {
    return codeNode(
      "json",
      fenceMeta(hikeCodeTitle(c.title) || "Request"),
      body,
    );
  }
  return codeNode("bash", fenceMeta("cURL"), curlCommand(body, DEVNET_RPC));
}

function convertMethod(
  node: AstNode,
  depth: number,
  file: ConvertFile,
  ctx: ConvertContext,
): AstNode[] {
  const kids = node.children ?? [];
  // `return-type` output starts at the <ResponseExample> / "Result" heading.
  let cut = kids.findIndex((k) => isJsx(k, "ResponseExample"));
  if (cut < 0)
    cut = kids.findIndex(
      (k, i) =>
        k.type === "heading" &&
        toText(k) === "Result" &&
        isJsx(kids[i + 1], "ResponseField"),
    );
  const head = cut < 0 ? kids : kids.slice(0, cut);
  const tail = cut < 0 ? [] : kids.slice(cut);
  const parsed = parseHikeSections(head);
  const where = file.path;

  if (parsed.children.some((s) => s.name === "result"))
    throw new Error(
      "APIMethod still has !!result sections: run return-type first",
    );

  const out: AstNode[] = [];
  const requests = parsed.code.filter((c) => c.name === "request");
  for (const c of parsed.code)
    if (c.name !== "request")
      ctx.warn(`${where}: unexpected APIMethod fence "!${c.name}" dropped`);
  if (requests.length) {
    out.push(
      jsx(
        "RequestExample",
        {},
        requests.map((c, i) =>
          requestFence(c, file, ctx, `${where} request ${i + 1}`),
        ),
      ),
    );
  } else ctx.warn(`${where}: APIMethod has no !!request fence`);

  const rest = [...tail];
  if (rest[0] && isJsx(rest[0], "ResponseExample")) out.push(rest.shift()!);

  // Content outside the slots was not rendered by the old component; keep it
  // (it is real prose) but say so.
  if (parsed.content.length) {
    ctx.warn(
      `${where}: ${parsed.content.length} node(s) outside APIMethod slots (hidden on the old site) kept`,
    );
    out.push(...parsed.content);
  }

  const params = parsed.children.filter((s) => s.name === "params");
  for (const s of parsed.children)
    if (s.name !== "params")
      ctx.warn(`${where}: unexpected APIMethod section "!${s.name}" dropped`);
  if (params.length > 1)
    ctx.warn(`${where}: ${params.length} !params sections`);
  out.push(heading(depth, "Parameters"));
  let any = false;
  for (const p of params) {
    reportValues(p, ctx, `${where} params`);
    out.push(...p.content);
    if (p.content.length) any = true;
    for (const f of fieldChildren(p, ctx, `${where} params`)) {
      out.push(renderField(f, "param", ctx, `${where} params`));
      any = true;
    }
  }
  // The old component printed "None" for a method without parameters.
  if (!any) out.push(paragraph([text("None")]));

  out.push(...rest);
  return out;
}

/** `<AccountsRpc />` -> `<SurfpoolAccounts />` + its snippet import. */
function convertSurfpool(tree: AstNode) {
  const needed = new Set<SurfpoolCategory>();
  walk(tree, (n) => {
    if (
      (n.type === "mdxJsxFlowElement" || n.type === "mdxJsxTextElement") &&
      typeof n.name === "string" &&
      n.name in SURFPOOL_COMPONENTS
    ) {
      const category = SURFPOOL_COMPONENTS[n.name]!;
      n.name = surfpoolImportName(category);
      n.attributes = [];
      n.children = [];
      needed.add(category);
    }
  });
  if (!needed.size) return;
  const kids = tree.children!;
  const have = new Set(
    kids.filter((k) => k.type === "mdxjsEsm").map((k) => String(k.value ?? "")),
  );
  const imports = [...needed]
    .sort()
    .map(
      (c) =>
        `import ${surfpoolImportName(c)} from "${surfpoolSnippetPath(c)}";`,
    )
    .filter((v) => !have.has(v))
    .map((value) => ({ type: "mdxjsEsm", value }) as AstNode);
  const at = kids[0]?.type === "yaml" ? 1 : 0;
  kids.splice(at, 0, ...imports);
}
