import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import {
  buildHeader,
  CSS_FILE,
  JS_FILE,
  messageKeys,
  runHeader,
  webSvgrOptions,
  type HeaderBuild,
} from "../src/header-bundle/build.ts";
import { docsRoot, repoRoot } from "../src/lib/paths.ts";

describe("gen:header helpers", () => {
  it("reads apps/web's SVGR options from next.config.ts", () => {
    const o = webSvgrOptions() as {
      svgoConfig?: { plugins?: Array<{ name: string }> };
    };
    expect(o.svgoConfig?.plugins?.[0]?.name).toBe("preset-default");
  });

  it("keeps the message keys (and t.raw subtrees) named by literals", () => {
    const en = {
      nav: { a: { title: "A", promo: { x: "1" } }, b: "B" },
      commands: { close: "Close" },
    };
    const keys = messageKeys(
      [
        `t("nav.a.title"); const k = "nav.a"; t('commands.close');`,
        `"nav.missing" "not.a.key" "nav.b"`,
      ],
      en,
    );
    // nav.a contains nav.a.title, so only the subtree is kept.
    expect(keys).toEqual(["commands.close", "nav.a", "nav.b"]);
  });
});

describe("gen:header bundle", () => {
  let built: HeaderBuild;
  beforeAll(async () => {
    built = await buildHeader();
  }, 180_000);

  it("bundles the real ui-chrome header and its imports", () => {
    for (const f of [
      "packages/ui-chrome/src/header.tsx",
      "packages/ui-chrome/src/header-list.tsx",
      "packages/ui-chrome/src/mobile-menu.tsx",
      "packages/ui-chrome/src/language-selector.tsx",
      "packages/ui-chrome/src/inkeep-searchbar.tsx",
      "packages/ui-chrome/src/link.tsx",
      "packages/ui-chrome/src/theme-provider.tsx",
      "packages/ui-chrome/src/assets/logotype.inline.svg",
    ])
      expect(built.inputs).toContain(f);
    // Next.js itself is never bundled (only the shims).
    expect(built.inputs.some((f) => /\/node_modules\/next\//.test(f))).toBe(
      false,
    );
    expect(built.inputs.some((f) => f.includes("@inkeep/cxkit-react"))).toBe(
      false,
    );
    expect(built.js.startsWith("/* GENERATED by")).toBe(true);
  });

  it("carries the header strings for the docs locales", () => {
    expect(built.keys).toContain("commands.search");
    expect(built.keys.some((k) => k.startsWith("nav.build"))).toBe(true);
    expect(built.js).toContain("Entwickeln"); // de: nav.build.title
  });

  it("scopes every compiled rule to #sol-hdr", () => {
    // Sections 1 (Tailwind base), 2 (apps/web element rules), 4 (utilities)
    // and 5 (apps/web globals) are generated; 3 is integration.css.
    const parts = built.css
      .split(/\/\* \d\. /)
      .map((p) => p.slice(p.indexOf("*/") + 2));
    const generated = [parts[1], parts[2], parts[4], parts[5]].join("\n");
    const selectors = [
      ...generated
        .replace(/@keyframes[^{]*\{(?:[^{}]*\{[^{}]*\})*[^{}]*\}/g, "")
        .replace(/\/\*[\s\S]*?\*\//g, "")
        .matchAll(/(?:^|[{};])\s*([^{};@]+?)\s*\{/g),
    ].map((m) => m[1]!);
    expect(selectors.length).toBeGreaterThan(300);
    const unscoped = selectors
      .flatMap((s) => s.split(","))
      .map((s) => s.trim())
      .filter((s) => s && !s.startsWith("#sol-hdr"));
    expect(unscoped).toEqual([]);
    expect(built.css).not.toMatch(/@keyframes (?!sol-hdr-)/);
  });

  it("--check passes on fresh output and fails on stale output", async () => {
    const dir = mkdtempSync(path.join(tmpdir(), "sol-header-"));
    mkdirSync(path.join(dir, "styles"));
    for (const f of [JS_FILE, CSS_FILE])
      writeFileSync(
        path.join(dir, f),
        readFileSync(path.join(docsRoot, f), "utf8"),
      );
    const fresh = await runHeader({ check: true, docsRoot: dir });
    expect(fresh.ok).toBe(true);
    writeFileSync(
      path.join(dir, JS_FILE),
      readFileSync(path.join(dir, JS_FILE), "utf8").replace(
        /hash [0-9a-f]+/,
        "hash 0000000000000000",
      ),
    );
    const stale = await runHeader({ check: true, docsRoot: dir });
    expect(stale.ok).toBe(false);
    expect(stale.written).toEqual([JS_FILE]);
  }, 180_000);

  // Sources are edited in memory (runHeader's `overrides`), never on disk.
  // Comment-only edits minify away, so these prove the input hash catches
  // them; code and string edits also change the bundle itself.
  it.each([
    ["packages/ui-chrome/src/header.tsx", (s: string) => `${s}\n// edited\n`],
    [
      "packages/ui-chrome/src/header.tsx",
      (s: string) => s.replace(/className="/, 'className="sol-test-edit '),
    ],
    [
      "packages/docs-tooling/src/header-bundle/runtime/shims/radix-portal.jsx",
      (s: string) => `${s}\n// edited\n`,
    ],
    [
      "packages/i18n/messages/web/de/common.json",
      (s: string) => `${s.trimEnd()}\n`.replace(/\n$/, "\n\n"),
    ],
  ])(
    "--check fails when a source changes: %s",
    async (rel, edit) => {
      const dir = mkdtempSync(path.join(tmpdir(), "sol-header-"));
      mkdirSync(path.join(dir, "styles"));
      for (const f of [JS_FILE, CSS_FILE])
        writeFileSync(
          path.join(dir, f),
          readFileSync(path.join(docsRoot, f), "utf8"),
        );
      const before = readFileSync(path.join(repoRoot, rel), "utf8");
      const after = edit(before);
      expect(after).not.toBe(before);
      const stale = await runHeader({
        check: true,
        docsRoot: dir,
        overrides: { [rel]: after },
      });
      expect(stale.ok).toBe(false);
      expect(stale.written).toEqual([JS_FILE, CSS_FILE]);
      // The repo file itself was not touched.
      expect(readFileSync(path.join(repoRoot, rel), "utf8")).toBe(before);
    },
    180_000,
  );
});
